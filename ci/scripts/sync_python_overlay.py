#!/usr/bin/env python3
"""Replace vllm_ascend's Python sources inside an existing image with a new tree.

Used by the python-overlay build: the base image already carries the CANN stack,
torch-npu, flash-attn and the compiled `vllm_ascend_C` extension, so only the
Python layer has to change. That is valid **only while `csrc/` is unchanged** --
the caller verifies that before the build starts, because an image whose .so
predates its .py would fail in obscure ways.

What this does:
  * copies every tracked file from the source tree over the installed package
  * deletes stale Python modules that the new tree no longer has
  * keeps compiled artefacts (.so) and anything the base image added
  * rewrites the recorded version so `vllm_ascend.__version__`, the dist-info
    metadata and `pip show` all agree with what was built
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import shutil
import sys

SKIP_DIRS = {'__pycache__'}


def installed_version(target: pathlib.Path) -> str | None:
    for candidate in target.parent.glob('vllm_ascend-*.dist-info'):
        metadata = candidate / 'METADATA'
        if not metadata.is_file():
            continue
        for line in metadata.read_text().splitlines():
            if line.startswith('Version: '):
                return line.split(': ', 1)[1].strip()
    return None


def version_tuple(version: str) -> tuple[str, ...]:
    """Split a PEP 440 version the way setuptools_scm records it.

    '0.30.0rc2.dev23+gabc1234' -> ('0', '30', '0', 'rc2', 'dev23', 'gabc1234')
    """
    base, local = version, None
    if '+' in base:
        base, local = base.split('+', 1)
    dev = None
    match = re.match(r'^(?P<release>\d+(?:\.\d+)*)(?P<pre>[ab]|rc)?(?P<pre_n>\d+)?', base)
    if not match:
        raise SystemExit(f'cannot split version: {version!r}')
    trailing = base[match.end():]
    dev_match = re.fullmatch(r'\.dev(\d+)', trailing)
    parts: list[str] = match.group('release').split('.')
    if match.group('pre'):
        parts.append(f"{match.group('pre')}{match.group('pre_n') or ''}")
    if dev_match:
        dev = f'dev{dev_match.group(1)}'
    elif trailing:
        raise SystemExit(f'unexpected version suffix: {trailing!r} in {version!r}')
    if dev:
        parts.append(dev)
    if local:
        parts.append(local)
    return tuple(parts)


def rewrite_version(target: pathlib.Path, version: str) -> list[str]:
    """Make every version surface agree. Returns the changes that were applied."""
    applied = []

    version_file = target / '_version.py'
    if True:
        version_file.write_text(
            '# file generated by vcs-versioning\n'
            '# don\'t change, don\'t track in version control\n'
            'from __future__ import annotations\n\n'
            '__all__ = [\n'
            '    "__version__",\n'
            '    "__version_tuple__",\n'
            '    "version",\n'
            '    "version_tuple",\n'
            '    "__commit_id__",\n'
            '    "commit_id",\n'
            ']\n\n'
            f'__version__ = version = {version!r}\n'
            f'__version_tuple__ = version_tuple = {version_tuple(version)!r}\n'
            '__commit_id__ = commit_id = None\n'
        )
        applied.append('_version.py')

    for dist_info in target.parent.glob('vllm_ascend-*.dist-info'):
        metadata = dist_info / 'METADATA'
        if metadata.is_file():
            lines = metadata.read_text().splitlines(keepends=True)
            patched = [
                f'Version: {version}\n' if line.startswith('Version: ') else line
                for line in lines
            ]
            metadata.write_text(''.join(patched))
            applied.append(f'{dist_info.name}/METADATA')
        renamed = dist_info.with_name(f'vllm_ascend-{version}.dist-info')
        if dist_info.name != renamed.name:
            try:
                shutil.move(str(dist_info), str(renamed))
                applied.append(f'renamed -> {renamed.name}')
            except OSError as error:
                # The venv can span mount layers, where rename is not atomic
                # (EXDEV). The METADATA rewrite above already carries the true
                # version, so report the directory name as stale rather than
                # failing a build over a cosmetic rename.
                applied.append(f'rename skipped ({error.__class__.__name__}); '
                               f'stale dist-info name {dist_info.name}')
    return applied


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', required=True, type=pathlib.Path)
    parser.add_argument('--target', required=True, type=pathlib.Path)
    parser.add_argument('--version', required=True)
    parser.add_argument('--commit', required=True)
    parser.add_argument('--base-version', default=None,
                        help='version already installed in the base image')
    parser.add_argument('--deleted-list', type=pathlib.Path, default=None,
                        help='files removed between the base commit and this one; '
                             'only these are deleted from the installed package')
    args = parser.parse_args()

    source, target = args.source.resolve(), args.target.resolve()
    if not source.is_dir():
        raise SystemExit(f'source tree missing: {source}')
    if not target.is_dir():
        raise SystemExit(f'installed package missing: {target}')
    before = installed_version(target)

    copied = 0
    for path in source.rglob('*'):
        if not path.is_file() or SKIP_DIRS & set(path.parts):
            continue
        destination = target / path.relative_to(source)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, destination)
        copied += 1

    # Delete only modules that git says disappeared between the base image's
    # source commit and this one. Scanning the target instead would also delete
    # build-generated modules that are legitimately absent from git
    # (_version.py, _build_info.py) and the vendored custom-op Python files.
    removed, missing_from_target = [], []
    if args.deleted_list and args.deleted_list.is_file():
        for line in args.deleted_list.read_text().splitlines():
            relative = line.strip()
            if not relative:
                continue
            path = target / relative
            if not path.is_file():
                missing_from_target.append(relative)
                continue
            path.unlink()
            removed.append(relative)
            cached = path.with_suffix(path.suffix + 'c')
            if cached.is_file():
                cached.unlink()

    for cache in target.rglob('__pycache__'):
        shutil.rmtree(cache, ignore_errors=True)

    applied = rewrite_version(target, args.version)

    identity = {
        'build_mode': 'python-overlay',
        'source_commit': args.commit,
        'version': args.version,
        'base_version': args.base_version or before,
        'files_copied': copied,
        'modules_removed': removed,
        'deleted_but_absent': missing_from_target,
        'version_surfaces_updated': applied,
    }
    (target.parent / 'SOURCE-IDENTITY.json').write_text(json.dumps(identity, indent=2) + '\n')

    print(f'overlay: copied {copied} files, removed {len(removed)} module(s) deleted upstream')
    for name in removed[:10]:
        print(f'  - {name}')
    if len(removed) > 10:
        print(f'  ... {len(removed) - 10} more')
    print(f'overlay: version {before} -> {args.version}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
